export const guides = allGuides.filter((guide) => !guide.draft);

export function getGuide(slug: string): Guide | undefined {
    return guides.find((g) => g.slug === slug);
}

export function guidesForProduct(productId: string): Guide[] {
    return guides.filter((g) => g.productIds.includes(productId));
}

export function guidesForHub(href: string): Guide[] {
    return guides.filter((g) => g.hubHref === href);
}
