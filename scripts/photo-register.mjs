#!/usr/bin/env node
/**
 * Photo register (specs/001-seo-geo-relaunch, T007, T041).
 *
 * Counts owner and stock photos per product from `data/products.ts` and the public folders, then writes
 * `data/photo-register.ts` and the «الصور المطلوبة» list in `docs/owner-updates.md`.
 * A product needs photos while it shows any stock photo or has fewer than MIN_OWNER photos of the owner's.
 *
 * Usage: node scripts/photo-register.mjs
 */
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const MIN_OWNER = 3;
const IMAGE = /\.(webp|jpe?g|png)$/i;
const START = '<!-- photos:start -->';
const END = '<!-- photos:end -->';

// What to shoot, most needed first: the pages that carry ads lead.
const SHOTS = {
    parket: 'باركيه مركّب في غرفة أو مجلس: صورة للغرفة كاملة، وصورة قريبة للألواح، وصورة لكل درجة لون',
    'water-resistant-carpet': 'باركيه ضد الماء مركّب في مطبخ أو ملحق، وصورة قريبة لقطعة تبيّن السماكة',
    'hospital-flooring': 'فينيل طبي مركّب في عيادة أو ممر مركز طبي، وصورة قريبة للوصلات ولقاء الأرضية بالجدار',
    mokite: 'موكيت مركّب في غرفة نوم ومجلس، وصورة قريبة للملمس، وصورة لعينات الألوان',
    'turky-mshager': 'موكيت تركي مشجر مفروش في مجلس، ورولات المعرض، وصورة قريبة لكل نقشة',
    'vinyl-mosque': 'فينيل مركّب في مسجد أو مصلى: صورة للمكان كامل، وصورة قريبة للفينيل',
    'office-flooring': 'فينيل مركّب في مكتب: ممر أو غرفة اجتماعات أو صالة موظفين',
    'artificial-grass': 'عشب صناعي مركّب في حوش أو سطح، وصورة قريبة للعشب',
};

const source = readFileSync('data/products.ts', 'utf8');
const blocks = source.split(/\n\s*id: "/).slice(1);

const folderPhotos = (dir) => {
    const path = join('public', dir);
    if (!existsSync(path)) return [];
    return readdirSync(path).filter((name) => IMAGE.test(name)).map((name) => join(path, name));
};

const register = blocks.map((block) => {
    const id = block.slice(0, block.indexOf('"'));
    const imageDir = block.match(/imageDir: "([^"]+)"/)?.[1];
    const listed = [...block.matchAll(/"(\/[^"]+\.(?:webp|jpe?g|png))"/gi)].map((match) => match[1]);
    const stock = listed.filter((src) => src.startsWith('/stock/')).length;
    const folder = imageDir ? folderPhotos(imageDir) : [];
    const outside = listed.filter((src) => !src.startsWith('/stock/') && !(imageDir && src.startsWith(`/${imageDir}/`)));
    const files = [...folder, ...outside.map((src) => join('public', src))].filter(existsSync);
    const newest = files.reduce((latest, file) => Math.max(latest, statSync(file).mtimeMs), 0);
    const owner = files.length;
    return {
        id,
        owner,
        stock,
        needed: stock > 0 || owner < MIN_OWNER,
        lastReceived: newest ? new Date(newest).toISOString().slice(0, 10) : null,
    };
});

writeFileSync(
    'data/photo-register.ts',
    `// Generated by scripts/photo-register.mjs. Do not edit by hand.
export interface PhotoRecord {
    id: string;
    owner: number;
    stock: number;
    needed: boolean;
    lastReceived: string | null;
}

export const photoRegister: PhotoRecord[] = ${JSON.stringify(register, null, 4)};
`,
);

const needed = Object.entries(SHOTS).filter(([id]) => register.find((record) => record.id === id)?.needed);
const known = new Set(Object.keys(SHOTS));
const unlisted = register.filter((record) => record.needed && !known.has(record.id)).map((record) => record.id);
const list = needed.map(([id, shots], index) => `${index + 1}. **${id}**: ${shots}.`).join('\n');
const doc = readFileSync('docs/owner-updates.md', 'utf8');
writeFileSync('docs/owner-updates.md', `${doc.slice(0, doc.indexOf(START) + START.length)}\n${list}\n${doc.slice(doc.indexOf(END))}`);

console.table(register);
if (unlisted.length) console.log(`Needs photos but has no shot list in SHOTS: ${unlisted.join(', ')}`);
